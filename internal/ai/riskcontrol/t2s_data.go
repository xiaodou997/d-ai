func tradToSimp(s string) string {
	out := make([]rune, 0, len(s))
	for _, r := range s {
		if simp, ok := t2sTable[r]; ok {
			out = append(out, simp)
		} else {
			out = append(out, r)
		}
	}
	return string(out)
}
